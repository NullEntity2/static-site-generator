import unittest
from textnode import TextNode, TextType, text_node_to_html_node


class TestTextNode(unittest.TestCase):
    def test_eq(self):
        node = TextNode("This is a text node", TextType.BOLD)
        node2 = TextNode("This is a text node", TextType.BOLD)
        self.assertEqual(node, node2)

    def test_not_eq(self):
        node = TextNode("This is a text node", TextType.BOLD)
        node2 = TextNode("This is a text node", TextType.ITALIC)
        self.assertNotEqual(node, node2)

    def test_constructor(self):
        node = TextNode("Hello", TextType.ITALIC, "test url")
        self.assertEqual(node.text, "Hello")
        self.assertEqual(node.text_type, TextType.ITALIC)
        self.assertEqual(node.url, "test url")

    def test_constructor_no_url(self):
        node = TextNode("Hello", TextType.ITALIC)
        self.assertEqual(node.text, "Hello")
        self.assertEqual(node.text_type, TextType.ITALIC)
        self.assertEqual(node.url, None)

    def test_text(self):
        node = TextNode("This is a text node", TextType.TEXT)
        html_node = text_node_to_html_node(node)
        self.assertEqual(html_node.tag, None)
        self.assertEqual(html_node.value, "This is a text node")

    def test_bold(self):
        node = TextNode("This is a bold node", TextType.BOLD)
        html_node = text_node_to_html_node(node)
        self.assertEqual(html_node.tag, "b")
        self.assertEqual(html_node.value, "This is a bold node")
    
    def test_italic(self):
        node = TextNode("This is a italic node", TextType.ITALIC)
        html_node = text_node_to_html_node(node)
        self.assertEqual(html_node.tag, "i")
        self.assertEqual(html_node.value, "This is a italic node")

    def test_code(self):
        node = TextNode("This is a code node", TextType.CODE)
        html_node = text_node_to_html_node(node)
        self.assertEqual(html_node.tag, "code")
        self.assertEqual(html_node.value, "This is a code node")

    def test_link(self):
        node = TextNode("This is a link node", TextType.LINK, "https://google.com/")
        html_node = text_node_to_html_node(node)
        self.assertEqual(html_node.tag, "a")
        self.assertEqual(html_node.value, "This is a link node")
        self.assertTrue(html_node.props)
        self.assertDictEqual(html_node.props, {"href": "https://google.com/"}) # type: ignore Narrowed by assertTrue

    def test_image(self):
        node = TextNode("This is an image node", TextType.IMAGE, "https://google.com/")
        html_node = text_node_to_html_node(node)
        self.assertEqual(html_node.tag, "img")
        self.assertEqual(html_node.value, None)
        self.assertTrue(html_node.props)
        self.assertDictEqual(html_node.props, {"src": "https://google.com/", "alt": "This is an image node"}) # type: ignore Narrowed by assertTrue





if __name__ == "__main__":
    unittest.main()